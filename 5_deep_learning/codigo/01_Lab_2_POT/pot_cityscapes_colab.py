"""---
## 📊 SECCIÓN 10 — Evaluación: mIoU, Dice y Pixel Accuracy

Evaluamos la calidad de los CAMs generados comparándolos con las máscaras ground truth.
Las métricas reportadas son:

- **mIoU** (mean Intersection over Union): métrica principal de Cityscapes
- **Dice coefficient**: 2*|A∩B|/(|A|+|B|) — complementa el IoU
- **Pixel Accuracy**: porcentaje de pixels correctamente clasificados

Para cada imagen, convertimos los CAMs prototípicos a una máscara de segmentación
y la comparamos con el ground truth (ignorando pixels con label=255).
"""

def evaluate(loader, n_samples=None):
    """
    Evalúa el modelo en mIoU, Dice y Pixel Accuracy.

    Args:
        loader   : DataLoader de validación
        n_samples: limitar a N imágenes (None = todas)

    Returns:
        dict con métricas promedio
    """
    model.eval()

    # Acumuladores por clase para IoU y Dice
    intersection = np.zeros(NUM_CLASSES)
    union        = np.zeros(NUM_CLASSES)
    dice_num     = np.zeros(NUM_CLASSES)
    dice_den     = np.zeros(NUM_CLASSES)
    total_correct = 0
    total_pixels  = 0
    processed     = 0

    with torch.no_grad():
        for images, img_labels, masks_gt in loader:
            images     = images.to(DEVICE)
            img_labels = img_labels.to(DEVICE)

            logits, cam_cls, feats, _ = model(images)
            B, _, H, W = feats.shape

            for b in range(B):
                feat_b  = feats[b]
                cam_b   = cam_cls[b]
                label_b = img_labels[b]
                mask_gt = masks_gt[b].numpy()    # [H, W] ground truth

                try:
                    cam_proto, _ = pot_forward_single(feat_b, cam_b, label_b, H, W)
                    # Upsample CAM al tamaño de la máscara GT
                    cam_up = F.interpolate(
                        cam_proto.unsqueeze(0), size=mask_gt.shape,
                        mode='bilinear', align_corners=False
                    ).squeeze(0)
                    seg_pred = cam_to_segmentation(cam_up).cpu().numpy()  # [H, W]
                    # Convertir índices: cam usa 0=bg,1..C=fg → gt usa 0..C-1 y 255
                    seg_fg = seg_pred - 1   # ahora 0..C-1, bg=-1
                except Exception:
                    seg_fg = np.full(mask_gt.shape, -1, dtype=np.int64)

                # Calcular métricas (ignorar pixels 255)
                valid = (mask_gt != 255)
                pred_valid = seg_fg[valid]
                gt_valid   = mask_gt[valid]

                # Pixel accuracy
                total_correct += (pred_valid == gt_valid).sum()
                total_pixels  += valid.sum()

                # IoU y Dice por clase
                for c in range(NUM_CLASSES):
                    pred_c = (pred_valid == c)
                    gt_c   = (gt_valid == c)
                    inter  = (pred_c & gt_c).sum()
                    uni    = (pred_c | gt_c).sum()
                    intersection[c] += inter
                    union[c]        += uni
                    dice_num[c]     += 2 * inter
                    dice_den[c]     += pred_c.sum() + gt_c.sum()

                processed += 1

            if n_samples and processed >= n_samples:
                break

    # Calcular métricas finales
    iou_per_class  = np.where(union > 0, intersection / union, np.nan)
    dice_per_class = np.where(dice_den > 0, dice_num / dice_den, np.nan)
    miou       = np.nanmean(iou_per_class)
    mean_dice  = np.nanmean(dice_per_class)
    pixel_acc  = total_correct / max(total_pixels, 1)

    return {
        'mIoU'       : float(miou),
        'Dice'       : float(mean_dice),
        'PixelAcc'   : float(pixel_acc),
        'iou_per_class' : iou_per_class,
        'dice_per_class': dice_per_class,
        'n_samples'  : processed
    }


print('✅ Función de evaluación implementada')
print('   Métricas: mIoU | Dice | Pixel Accuracy (ignorando label=255)')

