"""---
## 🔬 SECCIÓN 14 — Ablation Study

Reproducimos el ablation study del paper (Tabla 3 y 4) comparando:
- **Baseline** (I): single-cluster, sin OT, sin consistency loss
- **Condición II**: multi-cluster sin OT
- **Condición III**: multi-cluster + OT vanilla (distribución uniforme)
- **Condición IV (POT completo)**: multi-cluster + Similarity-aware OT + L_otcon

Esto permite verificar la contribución de cada componente en Cityscapes.
"""

def evaluate_ablation(use_multi_cluster=True, use_sot=True, use_otcon=True, n_samples=100):
    """
    Evalúa distintas configuraciones para el ablation study.

    Args:
        use_multi_cluster: True = K clusters, False = 1 cluster (baseline)
        use_sot          : True = similarity-aware OT, False = OT uniforme
        use_otcon        : True = OT consistency loss activa
    """
    model.eval()
    intersection = np.zeros(NUM_CLASSES)
    union        = np.zeros(NUM_CLASSES)
    processed    = 0
    K_use        = K_CLUSTERS if use_multi_cluster else 1

    with torch.no_grad():
        for images, img_labels, masks_gt in val_loader:
            images     = images.to(DEVICE)
            img_labels = img_labels.to(DEVICE)
            logits, cam_cls, feats, _ = model(images)
            B, _, H, W = feats.shape

            for b in range(B):
                feat_b  = feats[b]
                cam_b   = cam_cls[b]
                label_b = img_labels[b]
                mask_gt = masks_gt[b].numpy()

                try:
                    feats_flat = feat_b.reshape(feat_b.shape[0], -1)
                    cam_flat   = cam_b.reshape(cam_b.shape[0], -1)

                    cluster_protos, cls_protos, _, present = feature_partitioning(
                        feats_flat, cam_flat, label_b, K=K_use
                    )

                    if use_multi_cluster and len(present) > 0:
                        if use_sot:
                            T_star, assignment, _ = feature_allocation(
                                feats_flat, cluster_protos, cls_protos, present
                            )
                        else:
                            # OT uniforme (sin similarity-aware)
                            N = len(present) * K_use
                            x_unif = torch.full((N,), 1.0/N, device=DEVICE)
                            proto_list = [cluster_protos[c] for c in present]
                            all_p = torch.cat(proto_list, dim=0)
                            S = cosine_similarity_matrix(feats_flat.T.float(), all_p)
                            T_star  = sinkhorn_ot(S, x_unif)
                            assignment = T_star.argmax(dim=1)

                        cam_proto, _ = feature_activation(
                            feats_flat, cluster_protos, T_star, assignment, present, H, W
                        )
                    else:
                        # Single-cluster: usar CAM del clasificador directamente
                        cam_proto = cam_b

                    cam_up   = F.interpolate(cam_proto.unsqueeze(0), size=mask_gt.shape,
                                            mode='bilinear', align_corners=False).squeeze(0)
                    seg_pred = (cam_to_segmentation(cam_up).cpu().numpy() - 1)
                    seg_pred = np.clip(seg_pred, 0, NUM_CLASSES - 1)
                except Exception:
                    seg_pred = np.zeros(mask_gt.shape, dtype=np.int64)

                valid = (mask_gt != 255)
                for c in range(NUM_CLASSES):
                    pc = (seg_pred[valid] == c)
                    gc = (mask_gt[valid] == c)
                    intersection[c] += (pc & gc).sum()
                    union[c]        += (pc | gc).sum()

                processed += 1
            if processed >= n_samples:
                break

    iou = np.where(union > 0, intersection / union, np.nan)
    return float(np.nanmean(iou))


