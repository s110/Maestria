"""---
## 🔵 SECCIÓN 5 — POT Stage I: Feature Partitioning (K-Means + Prototipos)

Esta etapa implementa la **Sección 3.1** del paper:

1. Para cada clase presente en la imagen, seleccionamos los features con **CAM > τ** (features confiables)
2. Aplicamos **K-Means** con K=3 clusters sobre esos features confiables
3. Generamos un **prototipo** por cluster via Mask Average Pooling (MAP): `P = MAP(Mask · L(F1,F2,F3,F4))`
4. También generamos el **prototipo del clasificador CAM** `P_cls` (un solo prototipo global por clase)
   que se usará como referencia en la constraint del OT (Eq. 4 y 5)

El resultado es: `P ∈ R^{(J+1) × K × D}` — prototipos de cluster para J clases + background
"""

def mask_average_pool(features, mask):
    """
    Mask Average Pooling: MAP(Mask · Features)
    features: [D, H*W]  — features espaciales aplanadas
    mask    : [H*W]     — máscara binaria de la región
    Returns : [D]       — prototipo de la región
    """
    mask = mask.float()
    if mask.sum() < 1:
        return features.mean(dim=1)   # fallback: media global
    return (features * mask.unsqueeze(0)).sum(dim=1) / mask.sum()


def feature_partitioning(feats_flat, cam_cls, img_label, K=K_CLUSTERS, threshold=CAM_THRESHOLD):
    """
    Etapa I del paper (Sección 3.1): Feature Partitioning.

    Args:
        feats_flat : [D, HW]      features proyectadas aplanadas
        cam_cls    : [C+1, HW]    CAMs del clasificador (incluyendo background como clase 0)
        img_label  : [C]          etiqueta de imagen (qué clases están presentes)
        K          : int          número de clusters por clase
        threshold  : float        umbral τ para features confiables

    Returns:
        cluster_protos : [J+1, K, D]  prototipos de cluster (J clases + 1 background)
        cls_protos     : [J+1, D]     prototipos del clasificador CAM (1 por clase)
        cluster_masks  : [HW, J+1, K] máscara binaria de asignación inicial
        present_classes: list         índices de clases presentes (incluyendo background=0)
    """
    D, HW    = feats_flat.shape
    C        = img_label.shape[0]           # Número de clases foreground
    J1       = C + 1                        # Foreground + background
    feats_np = feats_flat.T.cpu().numpy()   # [HW, D] para sklearn

    cluster_protos = torch.zeros(J1, K, D, device=feats_flat.device)
    cls_protos     = torch.zeros(J1, D,    device=feats_flat.device)
    cluster_masks  = torch.zeros(HW, J1, K, device=feats_flat.device)
    present_classes = []

    # ── Background (clase 0) ─────────────────────────────────────────────────
    bg_cam    = cam_cls[0]                           # [HW]
    bg_conf   = (bg_cam > threshold).cpu().numpy()   # features confiables del bg
    # Prototipo del clasificador para background
    bg_mask_t = torch.from_numpy(bg_conf.astype(np.float32)).to(feats_flat.device)
    cls_protos[0] = mask_average_pool(feats_flat, bg_mask_t)

    if bg_conf.sum() >= K:
        try:
            km    = KMeans(n_clusters=K, n_init=3, random_state=SEED)
            labels = km.fit_predict(feats_np[bg_conf])
            conf_indices = np.where(bg_conf)[0]
            for k in range(K):
                k_indices = conf_indices[labels == k]
                if len(k_indices) > 0:
                    k_mask = torch.zeros(HW, device=feats_flat.device)
                    k_mask[k_indices] = 1.0
                    cluster_protos[0, k] = mask_average_pool(feats_flat, k_mask)
                    cluster_masks[:, 0, k] = k_mask
        except Exception:
            for k in range(K):
                cluster_protos[0, k] = cls_protos[0]
    else:
        for k in range(K):
            cluster_protos[0, k] = cls_protos[0]

    present_classes.append(0)

    # ── Clases foreground presentes ──────────────────────────────────────────
    fg_present = torch.where(img_label > 0.5)[0].tolist()

    for c in fg_present:
        class_idx  = c + 1                         # índice en cam_cls (bg=0)
        cam_c      = cam_cls[class_idx]             # [HW]
        conf_mask  = (cam_c > threshold).cpu().numpy()

        # Prototipo del clasificador para clase c (único, para la constraint)
        conf_t = torch.from_numpy(conf_mask.astype(np.float32)).to(feats_flat.device)
        cls_protos[class_idx] = mask_average_pool(feats_flat, conf_t)

        if conf_mask.sum() >= K:
            try:
                km     = KMeans(n_clusters=K, n_init=3, random_state=SEED)
                labels = km.fit_predict(feats_np[conf_mask])
                conf_indices = np.where(conf_mask)[0]
                for k in range(K):
                    k_indices = conf_indices[labels == k]
                    if len(k_indices) > 0:
                        k_mask = torch.zeros(HW, device=feats_flat.device)
                        k_mask[k_indices] = 1.0
                        cluster_protos[class_idx, k] = mask_average_pool(feats_flat, k_mask)
                        cluster_masks[:, class_idx, k] = k_mask
            except Exception:
                for k in range(K):
                    cluster_protos[class_idx, k] = cls_protos[class_idx]
        else:
            # Pocos features: repetir el prototipo único
            for k in range(K):
                cluster_protos[class_idx, k] = cls_protos[class_idx]

        present_classes.append(class_idx)

    return cluster_protos, cls_protos, cluster_masks, present_classes


print('✅ Feature Partitioning implementado')
print(f'   Salida: cluster_protos=[J+1={NUM_CLASSES+1}, K={K_CLUSTERS}, D={FEAT_DIM}]')

"""---
## 🔴 SECCIÓN 6 — POT Stage II: Feature Allocation (Similarity-Aware Optimal Transport)

Esta etapa implementa la **Sección 3.2** del paper — el corazón del método.

**Problema estándar de OT** (Eq. 3): encontrar el plan de transporte T que minimiza el costo
de mover masa de la distribución de features a la distribución de prototipos.

**Innovación del paper** (Eq. 5-6): en lugar de usar distribución uniforme en el target,
construimos una **constraint similarity-aware** `x = softmax(cosine_sim(P_cluster, P_cls))`
que prioriza los prototipos de cluster más similares al prototipo del clasificador.

Se resuelve con el **algoritmo de Sinkhorn** (OT regularizado) para eficiencia computacional.

Resultado: `T* ∈ R^{HW × (J+1)×K}` — plan de transporte que indica con qué probabilidad
cada feature pertenece a cada cluster.
"""

def cosine_similarity_matrix(A, B, eps=1e-8):
    """
    Calcula la matriz de similitud coseno entre filas de A y B.
    A: [M, D]  B: [N, D]  → Retorna [M, N]
    """
    A_norm = F.normalize(A.float(), dim=1, eps=eps)
    B_norm = F.normalize(B.float(), dim=1, eps=eps)
    return torch.mm(A_norm, B_norm.T)


def compute_similarity_aware_constraint(cluster_protos, cls_protos, present_classes):
    """
    Construye la restricción similarity-aware del target (Eq. 4-5 del paper).

    Para cada clase c y cluster k:
        x_{c,k} = cos_sim(P_{c,k}, P^cls_c)
    Luego: x = softmax(flatten(X))

    Args:
        cluster_protos : [J+1, K, D]
        cls_protos     : [J+1, D]
        present_classes: lista de índices de clases presentes

    Returns:
        x_constraint: [N] donde N = len(present_classes) * K
                      distribución normalizada del target (Eq. 5)
    """
    sims = []
    for c_idx in present_classes:
        p_cls = cls_protos[c_idx].unsqueeze(0)          # [1, D]
        p_clust = cluster_protos[c_idx]                  # [K, D]
        sim_ck = cosine_similarity_matrix(p_clust, p_cls).squeeze(1)  # [K]
        sims.append(sim_ck)

    X_flat = torch.cat(sims, dim=0)       # [N] = [len(present)*K]
    x      = F.softmax(X_flat, dim=0)    # Eq. 5: normalización
    return x


def sinkhorn_ot(S, x_constraint, reg=SINKHORN_REG, n_iter=SINKHORN_ITERS):
    """
    Sinkhorn OT implementado manualmente — sin librería POT.
    Matemáticamente equivalente a ot.sinkhorn().
    """
    M_cost = (1.0 - S).clamp(0, 2).float()
    K      = torch.exp(-M_cost / reg)        # Kernel: [HW, N]

    u = torch.full((S.shape[0],), 1.0 / S.shape[0], device=S.device)
    v = x_constraint.to(S.device).float()

    a = torch.ones(S.shape[0], device=S.device)
    b = torch.ones(len(x_constraint), device=S.device)

    for _ in range(n_iter):
        a = u / (K @ b + 1e-9)
        b = v / (K.T @ a + 1e-9)

    T_star = a.unsqueeze(1) * K * b.unsqueeze(0)
    return T_star


def feature_allocation(feats_flat, cluster_protos, cls_protos, present_classes):
    """
    Etapa II del paper (Sección 3.2): Feature Allocation con OT.

    Args:
        feats_flat     : [D, HW] features proyectadas
        cluster_protos : [J+1, K, D] prototipos de cluster
        cls_protos     : [J+1, D] prototipos del clasificador
        present_classes: lista de clases presentes

    Returns:
        T_star       : [HW, N] plan de transporte (N = len(present)*K)
        assignment   : [HW] índice del prototipo asignado a cada feature (Eq. 7)
        x_constraint : [N] restricción similarity-aware
    """
    D, HW = feats_flat.shape
    feats_T = feats_flat.T.float()   # [HW, D]

    # Construir matriz de prototipos para el OT: [N, D]
    proto_list = []
    for c_idx in present_classes:
        proto_list.append(cluster_protos[c_idx])    # [K, D]
    all_protos = torch.cat(proto_list, dim=0)       # [N, D]

    # Matriz de similitudes S [HW, N] (Eq. 6)
    S = cosine_similarity_matrix(feats_T, all_protos)

    # Restricción similarity-aware (Eq. 5)
    x_constraint = compute_similarity_aware_constraint(
        cluster_protos, cls_protos, present_classes
    )

    # Sinkhorn OT (Eq. 6)
    T_star = sinkhorn_ot(S, x_constraint)

    # Asignación greedy (Eq. 7): j* = argmax_j T*_{i,j}
    assignment = T_star.argmax(dim=1)   # [HW]

    return T_star, assignment, x_constraint


print('✅ Feature Allocation (Similarity-Aware OT) implementado')
print(f'   Sinkhorn: reg={SINKHORN_REG}, iters={SINKHORN_ITERS}')

"""---
## 🟢 SECCIÓN 7 — POT Stage III: Feature Activation + OT Consistency Loss

Esta etapa implementa la **Sección 3.3** del paper:

**Reweighting Prototype CAMs:**
1. Re-generar prototipos `P*` usando TODOS los features asignados a cada cluster (Eq. 8)
2. Calcular CAM de cada cluster: `M^p_{c,k} = ReLU(cos_sim(P*_{c,k}, L(F)))` (Eq. 9)
3. Reponderar: `M^{p→}_{c,k} = T*_{c,k} ⊙ M^p_{c,k}` (Eq. 10) — el plan OT como peso
4. Combinar: `M^{p→}_c = Σ_k M^{p→}_{c,k}` (Eq. 11)

**OT Consistency Loss (Eq. 12-14):**
Loss adaptativa que penaliza divergencia entre CAMs prototípicos y CAMs del clasificador,
con pesos por pixel `w_{i,c}` basados en la certeza del plan de transporte (entropía binaria).
"""

def feature_activation(feats_flat, cluster_protos, T_star, assignment,
                        present_classes, H, W, K=K_CLUSTERS):
    """
    Etapa III del paper (Sección 3.3): Feature Activation.

    Args:
        feats_flat     : [D, HW] features proyectadas
        cluster_protos : [J+1, K, D] prototipos de cluster iniciales
        T_star         : [HW, N] plan de transporte óptimo
        assignment     : [HW] asignación greedy de cada feature
        present_classes: lista de clases presentes
        H, W           : dimensiones espaciales del feature map

    Returns:
        cam_proto: [C+1, H, W] CAMs prototípicos finales (incluyendo background)
        T_star_restructured: plan de transporte organizado por clase
    """
    D, HW     = feats_flat.shape
    J1        = cluster_protos.shape[0]    # J+1 (clases + background)
    C         = J1 - 1                     # clases foreground
    feats_T   = feats_flat.T.float()       # [HW, D]

    # ── Re-generar prototipos con todos los features asignados (Eq. 8) ────────
    updated_protos = cluster_protos.clone()
    N_protos = len(present_classes) * K
    proto_idx = 0

    for c_pos, c_idx in enumerate(present_classes):
        for k in range(K):
            # Seleccionar features asignados a este prototipo
            assign_mask = (assignment == proto_idx).float()   # [HW]
            updated_protos[c_idx, k] = mask_average_pool(feats_flat, assign_mask)
            proto_idx += 1

    # ── Calcular CAMs por cluster (Eq. 9) ────────────────────────────────────
    # cam_proto_full: [J+1, H, W] — se va llenando por clase
    cam_proto_full = torch.zeros(J1, H, W, device=feats_flat.device)
    proto_idx = 0

    for c_pos, c_idx in enumerate(present_classes):
        cam_c_weighted = torch.zeros(HW, device=feats_flat.device)

        for k in range(K):
            # Cosine similarity entre prototipo actualizado y todos los features
            p_ck   = updated_protos[c_idx, k].unsqueeze(0)   # [1, D]
            sim_ck = cosine_similarity_matrix(feats_T, p_ck).squeeze(1)  # [HW]
            cam_ck = F.relu(sim_ck)                           # Eq. 9: ReLU

            # Pesos del plan de transporte para este prototipo (Eq. 10)
            t_ck          = T_star[:, proto_idx]              # [HW]
            cam_ck_weighted = t_ck * cam_ck                   # Eq. 10: reweighting
            cam_c_weighted += cam_ck_weighted                 # Eq. 11: suma
            proto_idx += 1

        # Reshape a espacial
        cam_proto_full[c_idx] = cam_c_weighted.reshape(H, W)

    return cam_proto_full, updated_protos


def binary_entropy(p, eps=1e-8):
    """Entropía binaria H(p) = -p*log(p) - (1-p)*log(1-p) (Eq. 14)"""
    p   = p.clamp(eps, 1 - eps)
    return -p * torch.log(p) - (1 - p) * torch.log(1 - p)


def ot_consistency_loss(cam_proto, cam_cls, T_star, img_label,
                        present_classes, K=K_CLUSTERS):
    """
    OT-based Consistency Loss (Eq. 12-14 del paper).

    Penaliza la divergencia entre CAMs prototípicos y CAMs del clasificador,
    con pesos adaptativos w_{i,c} basados en la certeza del plan OT.

    Args:
        cam_proto : [J+1, HW] CAMs prototípicos aplanados
        cam_cls   : [J+1, HW] CAMs del clasificador aplanados
        T_star    : [HW, N] plan de transporte
        img_label : [C] etiqueta de imagen
        present_classes: lista de clases presentes

    Returns:
        loss_otcon: escalar
    """
    HW       = cam_proto.shape[1]
    J1       = cam_proto.shape[0]
    C        = J1 - 1
    log_C1   = np.log(C + 1) + 1e-8    # Factor de escala 1/log(|C|+1)

    # Normalizar CAMs (ε1 normalización por clase para cada pixel)
    cam_proto_norm = F.normalize(cam_proto.float(), p=1, dim=0)
    cam_cls_norm   = F.normalize(cam_cls.float(),   p=1, dim=0)

    total_loss  = torch.tensor(0.0, device=cam_proto.device, requires_grad=False)
    proto_idx   = 0
    count       = 0

    for c_pos, c_idx in enumerate(present_classes):
        # g(t_{i,c}) = Σ_k t_{i,c,k} — prob de que feature i pertenezca a clase c (Eq. 13)
        t_ic = T_star[:, proto_idx:proto_idx+K].sum(dim=1)   # [HW]
        proto_idx += K

        # Entropía binaria (Eq. 14)
        H_t   = binary_entropy(t_ic)                          # [HW]

        # Peso adaptativo w_{i,c} (Eq. 13)
        # l_c = 1 si la clase está presente (one-hot), 0 si no
        l_c   = 1.0 if c_idx == 0 else float(img_label[c_idx - 1].item())
        w_ic  = l_c * (1.0 - H_t / log_C1)                   # [HW]
        w_ic  = w_ic.clamp(0)                                 # ≥ 0

        # L1 entre CAMs normalizados ponderado por w_{i,c}
        diff  = (cam_proto_norm[c_idx] - cam_cls_norm[c_idx]).abs()  # [HW]
        loss_c = (w_ic * diff).sum() / (HW + 1e-8)
        total_loss = total_loss + loss_c
        count += 1

    return total_loss / max(count, 1)


print('✅ Feature Activation y OT Consistency Loss implementados')

"""---
## 🔧 SECCIÓN 8 — Loss de clasificación y función POT completa

Aquí integramos todo el pipeline en una función `pot_forward` que:
1. Recibe un batch de imágenes y etiquetas débiles
2. Corre el encoder para obtener CAMs y features
3. Ejecuta las 3 etapas de POT imagen por imagen
4. Calcula la **loss total**: `L_total = L_cls + ϑ * L_otcon` (Eq. 15)

La **loss de clasificación** (Eq. 16) es multi-label soft margin:
`L_cls = (1/|C|) Σ_c [l_c * log(σ(GAP(ω_c^T · F))) + (1-l_c) * log(1 - σ(...))]`
"""

def classification_loss(logits, img_labels):
    """
    Multi-label soft margin loss (Eq. 16 del paper).
    logits    : [B, C]
    img_labels: [B, C] — etiquetas binarias de imagen
    """
    return F.multilabel_soft_margin_loss(logits, img_labels)


def pot_forward_single(feats, cam_cls, img_label, H, W):
    """
    Ejecuta el pipeline completo de POT para UNA imagen.

    Returns:
        cam_proto_full: [J+1, H, W] CAMs prototípicos finales
        loss_otcon    : escalar de consistency loss
    """
    D = feats.shape[0]
    # Aplanar: [D, HW]
    feats_flat = feats.reshape(D, -1)
    cam_flat   = cam_cls.reshape(cam_cls.shape[0], -1)   # [C+1, HW]

    # ── Stage I: Feature Partitioning ────────────────────────────────────────
    cluster_protos, cls_protos, _, present_classes = feature_partitioning(
        feats_flat, cam_flat, img_label
    )

    # ── Stage II: Feature Allocation (Sinkhorn OT) ───────────────────────────
    T_star, assignment, x_constraint = feature_allocation(
        feats_flat, cluster_protos, cls_protos, present_classes
    )

    # ── Stage III: Feature Activation ────────────────────────────────────────
    cam_proto_full, _ = feature_activation(
        feats_flat, cluster_protos, T_star, assignment,
        present_classes, H, W
    )

    # ── OT Consistency Loss ──────────────────────────────────────────────────
    cam_proto_flat = cam_proto_full.reshape(cam_proto_full.shape[0], -1)
    loss_otcon = ot_consistency_loss(
        cam_proto_flat, cam_flat, T_star, img_label, present_classes
    )

    return cam_proto_full, loss_otcon


def cam_to_segmentation(cam_proto, threshold=0.3):
    """
    Convierte CAMs prototípicos a máscara de segmentación.
    cam_proto: [J+1, H, W] — clase 0 es background
    Returns  : [H, W] — mapa de clases (0=background, 1..C=foreground)
    """
    # Normalizar
    cam_norm = cam_proto.clone()
    for c in range(cam_norm.shape[0]):
        mx = cam_norm[c].max()
        if mx > 0:
            cam_norm[c] /= mx

    # Asignar cada pixel a la clase con mayor activación
    seg_map = cam_norm.argmax(dim=0)   # [H, W] — índices 0=bg, 1..C=fg

    # Si la activación máxima es muy baja, marcar como background
    max_act  = cam_norm.max(dim=0)[0]
    seg_map[max_act < threshold] = 0

    return seg_map


