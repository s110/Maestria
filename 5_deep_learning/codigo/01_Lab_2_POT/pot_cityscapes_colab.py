"""---
## 🗃️ SECCIÓN 3 — Dataset y DataLoader de Cityscapes

Implementamos un Dataset personalizado que:
1. Carga imágenes RGB (`leftImg8bit`) y máscaras de ground truth (`gtFine_labelIds`)
2. Convierte los IDs originales de Cityscapes a índices 0-18
3. Genera **etiquetas de imagen** (image-level labels) a partir de las clases presentes en la máscara
   — esto simula la supervisión débil: en lugar de usar la máscara pixel a pixel durante el entrenamiento,
   solo usamos qué clases están presentes en la imagen.

> **Supervisión débil:** El modelo solo recibe un vector binario indicando qué clases hay en la imagen,
> NO la máscara de segmentación. Las máscaras solo se usan para **evaluar** la calidad de los CAMs.
"""

class CityscapesWeakDataset(Dataset):
    """
    Dataset de Cityscapes para entrenamiento con supervisión débil.
    Durante el entrenamiento: solo usa etiquetas de imagen (qué clases hay).
    Durante la evaluación: usa las máscaras ground truth para calcular mIoU.
    """
    def __init__(self, root, split='train', transform=None, mask_transform=None):
        self.root           = root
        self.split          = split
        self.transform      = transform
        self.mask_transform = mask_transform
        self.id_to_idx      = CITYSCAPES_ID_TO_IDX
        self.samples        = []
        self._build_file_list()

    def _build_file_list(self):
        img_dir = os.path.join(self.root, 'leftImg8bit_trainvaltest', 'leftImg8bit', self.split)
        gt_dir  = os.path.join(self.root, 'gtFine_trainvaltest', 'gtFine', self.split)
        for city in sorted(os.listdir(img_dir)):
            city_img_dir = os.path.join(img_dir, city)
            city_gt_dir  = os.path.join(gt_dir, city)
            for fname in sorted(os.listdir(city_img_dir)):
                if not fname.endswith('_leftImg8bit.png'):
                    continue
                prefix   = fname.replace('_leftImg8bit.png', '')
                gt_fname = prefix + '_gtFine_labelIds.png'
                img_path = os.path.join(city_img_dir, fname)
                gt_path  = os.path.join(city_gt_dir, gt_fname)
                if os.path.exists(gt_path):
                    self.samples.append((img_path, gt_path))
        print(f'   [{self.split}] {len(self.samples)} muestras cargadas')

    def _label_ids_to_idx(self, mask_pil):
        """Convierte máscara de IDs originales a índices 0-18 (255 = ignore)."""
        mask_np  = np.array(mask_pil, dtype=np.int32)
        out_mask = np.full(mask_np.shape, 255, dtype=np.uint8)
        for orig_id, idx in self.id_to_idx.items():
            out_mask[mask_np == orig_id] = idx
        return out_mask

    def _get_image_label(self, mask_idx):
        """Vector binario [NUM_CLASSES] indicando qué clases están presentes."""
        label = torch.zeros(NUM_CLASSES, dtype=torch.float32)
        unique = np.unique(mask_idx)
        for u in unique:
            if 0 <= u < NUM_CLASSES:
                label[u] = 1.0
        return label

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        img_path, gt_path = self.samples[idx]
        image    = Image.open(img_path).convert('RGB')
        mask_pil = Image.open(gt_path)

        # Convertir IDs a índices 0-18
        mask_idx = self._label_ids_to_idx(mask_pil)

        # Etiqueta de imagen (supervisión débil)
        img_label = self._get_image_label(mask_idx)

        # Transformaciones
        if self.transform:
            image = self.transform(image)

        # Máscara para evaluación
        mask_tensor = torch.from_numpy(mask_idx).long()
        if self.mask_transform:
            mask_pil_tmp = Image.fromarray(mask_idx)
            mask_tensor  = torch.from_numpy(
                np.array(mask_pil_tmp.resize((IMG_SIZE, IMG_SIZE), Image.NEAREST))
            ).long()
        else:
            mask_tensor = torch.from_numpy(
                np.array(Image.fromarray(mask_idx).resize(
                    (IMG_SIZE, IMG_SIZE), Image.NEAREST))
            ).long()

        return image, img_label, mask_tensor


