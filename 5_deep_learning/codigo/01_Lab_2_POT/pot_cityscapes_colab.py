"""---
## 🏗️ SECCIÓN 4 — Arquitectura: Encoder (ResNet50) + Clasificador + CAM

Implementamos el **Encoder** basado en ResNet50 pre-entrenado en ImageNet (como en el paper).

El encoder expone los features de las 4 capas (F1, F2, F3, F4) necesarios para la proyección
jerárquica de la Eq. (2) y (8) del paper. El clasificador usa Global Average Pooling (GAP)
seguido de una capa lineal para predecir qué clases están presentes (Eq. 16).

Los **CAMs del clasificador** se generan como: `CAM_c = ReLU(W_c^T · F4)` (Eq. 1 del paper).
"""

class HierarchicalProjection(nn.Module):
    """
    Proyección lineal L(F1, F2, F3, F4) del paper (Eq. 2 y 8).
    Combina features de múltiples capas del encoder en una representación unificada.
    Canales de ResNet50: F1=256, F2=512, F3=1024, F4=2048 → proyecta a FEAT_DIM.
    """
    def __init__(self, out_dim=2048):
        super().__init__()
        # Cada capa se proyecta al espacio de features final
        self.proj1 = nn.Conv2d(256,  out_dim, kernel_size=1, bias=False)
        self.proj2 = nn.Conv2d(512,  out_dim, kernel_size=1, bias=False)
        self.proj3 = nn.Conv2d(1024, out_dim, kernel_size=1, bias=False)
        self.proj4 = nn.Conv2d(2048, out_dim, kernel_size=1, bias=False)
        self.bn    = nn.BatchNorm2d(out_dim)
        self.relu  = nn.ReLU(inplace=True)

    def forward(self, f1, f2, f3, f4):
        H, W = f4.shape[2], f4.shape[3]
        p1 = F.interpolate(self.proj1(f1), size=(H, W), mode='bilinear', align_corners=False)
        p2 = F.interpolate(self.proj2(f2), size=(H, W), mode='bilinear', align_corners=False)
        p3 = F.interpolate(self.proj3(f3), size=(H, W), mode='bilinear', align_corners=False)
        p4 = self.proj4(f4)
        return self.relu(self.bn(p1 + p2 + p3 + p4))


class POTEncoder(nn.Module):
    """
    Encoder basado en ResNet50 preentrenado en ImageNet.
    Expone F1, F2, F3, F4 para la proyección jerárquica.
    Incluye el clasificador multi-label y la generación de CAMs.
    """
    def __init__(self, num_classes=NUM_CLASSES, feat_dim=FEAT_DIM):
        super().__init__()
        backbone = models.resnet50(weights=ResNet50_Weights.IMAGENET1K_V1)

        # ── Extraer capas del backbone ───────────────────────────────────────
        self.layer0 = nn.Sequential(backbone.conv1, backbone.bn1,
                                    backbone.relu, backbone.maxpool)
        self.layer1 = backbone.layer1   # → [B, 256,  H/4,  W/4]
        self.layer2 = backbone.layer2   # → [B, 512,  H/8,  W/8]
        self.layer3 = backbone.layer3   # → [B, 1024, H/16, W/16]
        self.layer4 = backbone.layer4   # → [B, 2048, H/32, W/32] = F4

        # ── Proyección jerárquica L(F1,F2,F3,F4) ────────────────────────────
        self.hier_proj = HierarchicalProjection(out_dim=feat_dim)

        # ── Clasificador: peso ω_c para cada clase (Eq. 1 y 16) ─────────────
        self.classifier = nn.Linear(feat_dim, num_classes, bias=False)

        self.num_classes = num_classes
        self.feat_dim    = feat_dim

    def forward(self, x):
        """
        Returns:
            logits     : [B, C] predicciones de clasificación
            cam_cls    : [B, C+1, H, W] CAMs del clasificador (incluyendo background)
            feats      : [B, D, H, W] features jerárquicas proyectadas
            f1,f2,f3,f4: features crudas por capa
        """
        # ── Forward por el backbone ──────────────────────────────────────────
        x  = self.layer0(x)
        f1 = self.layer1(x)    # [B, 256,  H/4,  W/4]
        f2 = self.layer2(f1)   # [B, 512,  H/8,  W/8]
        f3 = self.layer3(f2)   # [B, 1024, H/16, W/16]
        f4 = self.layer4(f3)   # [B, 2048, H/32, W/32]

        # ── Proyección jerárquica ────────────────────────────────────────────
        feats = self.hier_proj(f1, f2, f3, f4)   # [B, D, H, W]

        # ── Clasificador (GAP + linear) ──────────────────────────────────────
        gap    = F.adaptive_avg_pool2d(feats, 1).flatten(1)  # [B, D]
        logits = self.classifier(gap)                         # [B, C]

        # ── CAMs del clasificador: ReLU(W_c^T · feats) (Eq. 1) ──────────────
        W = self.classifier.weight   # [C, D]
        # Foreground CAMs: [B, C, H, W]
        cam_fg = F.relu(
            torch.einsum('cd,bdhw->bchw', W, feats)
        )
        # Normalizar cada CAM a [0, 1]
        cam_max = cam_fg.flatten(2).max(dim=2)[0].unsqueeze(-1).unsqueeze(-1) + 1e-8
        cam_fg  = cam_fg / cam_max

        # Background CAM: 1 - max_c(cam_fg_c) (Eq. 1 del paper)
        cam_bg  = 1.0 - cam_fg.max(dim=1, keepdim=True)[0]  # [B, 1, H, W]

        # CAM completo con background como clase 0
        cam_cls = torch.cat([cam_bg, cam_fg], dim=1)          # [B, C+1, H, W]

        return logits, cam_cls, feats, (f1, f2, f3, f4)


